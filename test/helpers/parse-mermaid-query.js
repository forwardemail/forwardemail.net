const test = require('ava');
const { JSDOM } = require('jsdom');

const env = require('#config/env');
const markdown = require('#helpers/markdown');
const { encrypt } = require('#helpers/encrypt-decrypt');
const parseMermaidQuery = require('#helpers/parse-mermaid-query');

function context(query) {
  return {
    query,
    translateError(key) {
      return key;
    }
  };
}

// the `code` query parameter the markdown renderer links to
function renderMermaidCode(code) {
  const html = markdown.render(`\`\`\`mermaid\n${code}\n\`\`\`\n`);
  const { document } = new JSDOM(html).window;
  const src = document.querySelector('img').getAttribute('src');
  return new URL(src, 'https://example.com').searchParams.get('code');
}

test('rejects malformed Mermaid image parameters before rendering', (t) => {
  for (const query of [
    {},
    { code: 'not-an-encrypted-payload' },
    { code: 'not-an-encrypted-payload', theme: 'light' },
    { code: 'not-an-encrypted-payload', theme: 'dark' }
  ]) {
    const err = t.throws(() => parseMermaidQuery(context(query)));
    t.is(err.output.statusCode, 400);
    t.is(err.output.payload.message, 'UNKNOWN_ERROR');
  }
});

test('accepts a Mermaid code generated by the markdown renderer', (t) => {
  const code =
    'gantt\n  title Example\n  section Plan\n  Task :a1, 2025-01-01, 1d';
  t.deepEqual(
    parseMermaidQuery(
      context({ code: renderMermaidCode(code), theme: 'dark' })
    ),
    { code, theme: 'dark' }
  );
});

test('rejects values encrypted with the shared helper keys', (t) => {
  // other features return values encrypted with these keys (some of them
  // user-chosen), so they must never be accepted as a diagram
  const code = 'graph TD\n  A[<img src="http://169.254.169.254/">] --> B';
  const keys = [env.HELPER_ENCRYPTION_KEY];
  if (env.HELPER_ENCRYPTION_KEY_LEGACY)
    keys.push(env.HELPER_ENCRYPTION_KEY_LEGACY);

  for (const key of keys) {
    const err = t.throws(() =>
      parseMermaidQuery(
        context({ code: encrypt(code, undefined, key), theme: 'default' })
      )
    );
    t.is(err.output.statusCode, 400);
    t.is(err.output.payload.message, 'UNKNOWN_ERROR');
  }
});
